using System.Globalization;
using System.Text;
using HearSay.Synthesis.Export;
using HearSay.Synthesis.Patches;
using HearSay.Synthesis.Profiles;
using HearSay.Synthesis.Rendering;

namespace HearSay.SuperCollider.FM7;

/// <summary>
/// Writes a canonical patch as a self-contained SuperCollider SynthDef around the <c>FM7</c> UGen of the
/// sc3-plugins. The generated code needs SuperCollider and sc3-plugins only, never HearSay.
/// </summary>
/// <remarks>
/// <para>Mapping, verified against the FM7 source and against renders of the real UGen:</para>
/// <list type="bullet">
/// <item><c>FM7.ar(ctlMatrix, modMatrix)</c> with the full matrix interface; <c>FM7.arAlgo</c> is never used.</item>
/// <item><c>ctlMatrix</c> has one row <c>[frequency, phase, amplitude]</c> per operator, all control rate.</item>
/// <item>
/// <c>modMatrix[destination][source]</c> is the phase deviation in radians per unit of source output, the same
/// orientation and unit as <see cref="PhaseModulationMatrix"/>. The diagonal is self-feedback.
/// </item>
/// <item>FM7 returns the six operator outputs; they are mixed with the canonical output levels.</item>
/// </list>
/// <para>Stateless and thread-safe.</para>
/// </remarks>
public sealed class SuperColliderFm7Exporter : IPatchExporter
{
    /// <inheritdoc />
    public SynthesisCapabilities Capabilities => SynthesisProfiles.SuperColliderFm7.Capabilities;

    /// <inheritdoc />
    public string FileExtension => ".scd";

    /// <inheritdoc />
    public string Export(OperatorMatrixPatch patch, PatchExportOptions? options = null)
    {
        options ??= new PatchExportOptions();
        string name = options.InstrumentName;
        var text = new StringBuilder();
        text.Append("// Generated by HearSay. Needs SuperCollider with sc3-plugins (FM7 UGen); HearSay itself is not needed.\n");
        foreach (string comment in options.HeaderComments)
        {
            text.Append("// ").Append(comment.ReplaceLineEndings(" ")).Append('\n');
        }

        text.Append("//\n");
        text.Append("// Controls: freq (Hz), gate, velocity (0..1), amp, out.\n");
        text.Append("// Ratio operators follow freq, fixed operators do not.\n");
        text.Append("// modMatrix[destination][source] is in radians; the diagonal is self-feedback.\n");
        text.Append("(\n");
        text.Append(ExportSynthDef(patch, name));
        text.Append(".add;\n)\n");
        if (options.IncludeUsageExample)
        {
            text.Append('\n');
            text.Append("// Play a note:\n");
            text.Append("(\n");
            text.Append("fork {\n");
            text.Append("\tvar note = Synth(\\").Append(name).Append(", [\\freq, 60.midicps, \\velocity, 0.8, \\amp, 0.2]);\n");
            text.Append("\t1.5.wait;\n");
            text.Append("\tnote.set(\\gate, 0);\n");
            text.Append("};\n");
            text.Append(")\n");
            text.Append('\n');
            text.Append("// Or play it as an instrument:\n");
            text.Append("(\n");
            text.Append("Pbind(\n");
            text.Append("\t\\instrument, \\").Append(name).Append(",\n");
            text.Append("\t\\midinote, Pseq([48, 55, 60, 64, 67, 72], 2),\n");
            text.Append("\t\\velocity, Pwhite(0.5, 1.0),\n");
            text.Append("\t\\dur, 0.5,\n");
            text.Append("\t\\legato, 0.8,\n");
            text.Append("\t\\amp, 0.2\n");
            text.Append(").play;\n");
            text.Append(")\n");
        }

        return text.ToString();
    }

    /// <summary>
    /// Returns only the <c>SynthDef(...)</c> expression, without <c>.add</c>, for callers that send the definition to
    /// a server themselves, such as a non-realtime render.
    /// </summary>
    /// <param name="patch">Patch to export.</param>
    /// <param name="synthDefName">Name of the SynthDef.</param>
    /// <exception cref="PatchNotSupportedException">FM7 cannot represent the patch.</exception>
    public string ExportSynthDef(OperatorMatrixPatch patch, string synthDefName = "HearSayPatch")
    {
        ArgumentNullException.ThrowIfNull(patch);
        ArgumentException.ThrowIfNullOrWhiteSpace(synthDefName);
        foreach (char c in synthDefName)
        {
            if (!char.IsAsciiLetterOrDigit(c) && c != '_')
            {
                throw new ArgumentException("A SynthDef name may contain ASCII letters, digits and underscores only.", nameof(synthDefName));
            }
        }

        PatchCompatibilityResult compatibility = PatchCompatibilityValidator.Instance.Validate(patch, Capabilities);
        if (!compatibility.IsCompatible)
        {
            throw new PatchNotSupportedException("SuperCollider FM7", compatibility);
        }

        int n = patch.OperatorCount;
        bool[] audible = patch.FindAudibleOperators();
        bool movingPitch = !patch.Pitch.IsStatic;
        bool needsNote = false;
        for (int i = 0; i < n; i++)
        {
            needsNote |= audible[i] && !patch.Operators[i].KeyScaling.IsNeutral;
        }

        var text = new StringBuilder();
        text.Append("SynthDef(\\").Append(synthDefName).Append(", { |out = 0, freq = 440, gate = 1, velocity = 1, amp = 0.2|\n");
        text.Append("\tvar ctlMatrix, modMatrix, operators, signal;\n");
        if (needsNote)
        {
            text.Append("\tvar note = freq.cpsmidi;\n");
        }

        if (movingPitch)
        {
            text.Append("\tvar pitch = (").Append(PitchCents(patch.Pitch)).Append(" / 100).midiratio;\n");
        }

        text.Append('\n');
        text.Append("\t// One row per operator: [frequency, phase, amplitude].\n");
        text.Append("\tctlMatrix = [\n");
        for (int i = 0; i < n; i++)
        {
            text.Append("\t\t");
            text.Append(audible[i] ? OperatorRow(patch.Operators[i], movingPitch) : "[0, 0, 0]");
            text.Append(i < n - 1 ? "," : string.Empty);
            text.Append(" // OP").Append(i + 1);
            if (!audible[i])
            {
                text.Append(patch.Operators[i].Enabled ? " (inaudible)" : " (off)");
            }

            text.Append('\n');
        }

        text.Append("\t];\n\n");
        text.Append("\t// modMatrix[destination][source], radians. Columns: OP1 .. OP").Append(n).Append(".\n");
        text.Append("\tmodMatrix = [\n");
        for (int d = 0; d < n; d++)
        {
            text.Append("\t\t[");
            for (int s = 0; s < n; s++)
            {
                ModulationEdge? edge = patch.ModulationMatrix.Find(s, d);
                bool live = edge is { Enabled: true } && edge.Amount != 0.0 && audible[s] && audible[d];
                text.Append(live ? EdgeAmount(edge!) : "0");
                text.Append(s < n - 1 ? ", " : string.Empty);
            }

            text.Append(']').Append(d < n - 1 ? "," : string.Empty).Append(" // into OP").Append(d + 1).Append('\n');
        }

        text.Append("\t];\n\n");
        text.Append("\toperators = FM7.ar(ctlMatrix, modMatrix);\n");
        text.Append("\tsignal = (operators * [");
        for (int i = 0; i < n; i++)
        {
            text.Append(audible[i] ? Number(patch.OutputLevels[i]) : "0").Append(i < n - 1 ? ", " : string.Empty);
        }

        text.Append("]).sum;\n\n");
        text.Append("\t// Frees the synth when the note is over.\n");
        text.Append('\t').Append(Lifetime(patch, audible)).Append('\n');
        text.Append("\tOut.ar(out, (signal * amp) ! 2);\n");
        text.Append("})");
        return text.ToString();
    }

    private static string OperatorRow(OperatorPatch op, bool movingPitch)
    {
        var row = new StringBuilder("[");
        if (op.Frequency.Mode == OperatorFrequencyMode.Ratio)
        {
            double factor = op.Frequency.Ratio * Math.Pow(2.0, op.FineTuneCents / 1200.0);
            row.Append("(freq * ").Append(Number(factor));
            if (movingPitch)
            {
                row.Append(" * pitch");
            }

            row.Append(')');
            if (op.DetuneHz != 0.0)
            {
                row.Append(" + ").Append(Number(op.DetuneHz));
            }
        }
        else
        {
            row.Append(Number(op.Frequency.FixedFrequencyHz + op.DetuneHz));
        }

        row.Append(", ").Append(Number(op.InitialPhase)).Append(", ");
        string? timeScale = op.KeyScaling.RatePerOctave != 0.0
            ? $"(2 ** ({Number(-op.KeyScaling.RatePerOctave)} * ((note - {Number(op.KeyScaling.ReferenceMidiNote)}) / 12)))"
            : null;
        row.Append(EnvGen(op.AmplitudeEnvelope, timeScale));
        if (op.VelocitySensitivity != 0.0)
        {
            row.Append(" * (").Append(Number(1.0 - op.VelocitySensitivity)).Append(" + (").Append(Number(op.VelocitySensitivity)).Append(" * velocity))");
        }

        if (op.KeyScaling.LevelDbPerOctave != 0.0)
        {
            row.Append(" * (").Append(Number(op.KeyScaling.LevelDbPerOctave)).Append(" * ((note - ").Append(Number(op.KeyScaling.ReferenceMidiNote)).Append(") / 12)).dbamp");
        }

        row.Append(']');
        return row.ToString();
    }

    private static string EdgeAmount(ModulationEdge edge) =>
        edge.AmountEnvelope is null
            ? Number(edge.Amount)
            : $"({Number(edge.Amount)} * {EnvGen(edge.AmountEnvelope, null)})";

    private static string PitchCents(PitchModel pitch)
    {
        var parts = new List<string>();
        if (pitch.PitchEnvelope is not null)
        {
            parts.Add(EnvGen(pitch.PitchEnvelope, null));
        }

        if (pitch.Vibrato is { DepthCents: not 0.0 } vibrato)
        {
            string lfo = $"(SinOsc.kr({Number(vibrato.RateHz)}) * {Number(vibrato.DepthCents)}";
            if (vibrato.DelaySeconds > 0 || vibrato.FadeInSeconds > 0)
            {
                lfo += $" * EnvGen.kr(Env([0, 0, 1], [{Number(vibrato.DelaySeconds)}, {Number(vibrato.FadeInSeconds)}]))";
            }

            parts.Add(lfo + ")");
        }

        return "(" + string.Join(" + ", parts) + ")";
    }

    private static string EnvGen(OperatorEnvelope envelope, string? timeScale)
    {
        var levels = new StringBuilder();
        var times = new StringBuilder();
        var curves = new StringBuilder();
        for (int i = 0; i < envelope.Points.Count; i++)
        {
            levels.Append(i > 0 ? ", " : string.Empty).Append(Number(envelope.EffectiveLevel(i)));
            if (i > 0)
            {
                times.Append(i > 1 ? ", " : string.Empty).Append(Number(envelope.Points[i].TimeSeconds));
                curves.Append(i > 1 ? ", " : string.Empty).Append(envelope.Points[i].Curve switch
                {
                    EnvelopeCurve.Exponential => "\\exp",
                    EnvelopeCurve.Step => "\\step",
                    _ => "\\lin",
                });
            }
        }

        var text = new StringBuilder();
        text.Append("EnvGen.kr(Env([").Append(levels).Append("], [").Append(times).Append("], [").Append(curves).Append(']');
        if (envelope.SustainPoint is int sustain)
        {
            text.Append(", ").Append(sustain.ToString(CultureInfo.InvariantCulture));
        }

        text.Append("), gate");
        if (timeScale is not null)
        {
            text.Append(", timeScale: ").Append(timeScale);
        }

        text.Append(')');
        return text.ToString();
    }

    private static string Lifetime(OperatorMatrixPatch patch, bool[] audible)
    {
        bool sustaining = false;
        double release = 0;
        double oneShot = 0;
        for (int i = 0; i < patch.OperatorCount; i++)
        {
            if (!audible[i] || patch.OutputLevels[i] == 0.0)
            {
                continue;
            }

            OperatorPatch op = patch.Operators[i];
            OperatorEnvelope envelope = op.AmplitudeEnvelope;

            // Key scaling can stretch envelopes; four octaves below the reference note is a generous bound.
            double stretch = Math.Max(1.0, Math.Pow(2.0, Math.Abs(op.KeyScaling.RatePerOctave) * 4.0));
            if (envelope.SustainPoint is null)
            {
                double total = 0;
                for (int p = 1; p < envelope.Points.Count; p++)
                {
                    total += envelope.Points[p].TimeSeconds;
                }

                oneShot = Math.Max(oneShot, total * stretch);
            }
            else
            {
                sustaining = true;
                release = Math.Max(release, envelope.ReleaseSeconds * stretch);
            }
        }

        return sustaining
            ? $"EnvGen.kr(Env.asr(0, 1, {Number(Math.Max(release, oneShot) + 0.05)}, \\lin), gate, doneAction: Done.freeSelf);"
            : $"Line.kr(0, 1, {Number(oneShot + 0.05)}, doneAction: Done.freeSelf);";
    }

    /// <summary>Formats a number as a SuperCollider float literal that reads back as the same 32-bit value.</summary>
    internal static string Number(double value)
    {
        string text = ((float)value).ToString("R", CultureInfo.InvariantCulture);
        if (text.Contains('E', StringComparison.Ordinal))
        {
            // SuperCollider needs a digit on both sides of the decimal point and a lower-case exponent.
            // Through decimal, so that the shortest round-trip digits survive: 1E-05 becomes 0.00001.
            text = decimal.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out decimal exact)
                ? exact.ToString("0.0###########################", CultureInfo.InvariantCulture)
                : ((double)(float)value).ToString("0.0###############", CultureInfo.InvariantCulture);
        }
        else if (!text.Contains('.', StringComparison.Ordinal))
        {
            text += ".0";
        }

        return text;
    }
}
