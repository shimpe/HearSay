using System.Globalization;
using HearSay.Synthesis.Export;
using HearSay.Synthesis.Patches;
using HearSay.Synthesis.Profiles;
using HearSay.Synthesis.Rendering;

namespace HearSay.SuperCollider;

/// <summary>
/// Writes a canonical patch as a self-contained SuperCollider SynthDef around a six-operator phase-modulation UGen.
/// Subclasses name the UGen (<c>FM7</c> from sc3-plugins, or <c>FMX6</c>); the generated code never needs HearSay.
/// </summary>
/// <remarks>
/// <para>Mapping, verified against the FM7 source and against renders of the real UGen:</para>
/// <list type="bullet">
/// <item><c>UGen.ar(ctlMatrix, modMatrix, ...)</c> with the full matrix interface; <c>FM7.arAlgo</c> is never used.</item>
/// <item><c>ctlMatrix</c> has one row <c>[frequency, phase, amplitude]</c> per operator, all control rate.</item>
/// <item>
/// <c>modMatrix[destination][source]</c> is the phase deviation in radians per unit of source output, the same
/// orientation and unit as <see cref="PhaseModulationMatrix"/>. The diagonal is self-feedback.
/// </item>
/// <item>The UGen returns the six operator outputs; they are mixed with the canonical output levels.</item>
/// </list>
/// <para>Stateless and thread-safe.</para>
/// </remarks>
public abstract class SuperColliderOperatorMatrixExporter : IPatchExporter, ISynthDefExporter
{
    /// <inheritdoc />
    public abstract SynthesisCapabilities Capabilities { get; }

    /// <summary>Name of the backend for messages, for example "SuperCollider FM7".</summary>
    public abstract string BackendName { get; }

    /// <inheritdoc />
    public abstract int ControlBlockSize { get; }

    /// <summary>What the generated code needs, for the header comment, for example "sc3-plugins (FM7 UGen)".</summary>
    protected abstract string Requirement { get; }

    /// <summary>The statement that assigns the six operator outputs to <c>operators</c>, without leading tab or trailing newline.</summary>
    /// <param name="patch">Patch being exported.</param>
    /// <param name="audible">Which operators are audible; the others get silent rows.</param>
    protected abstract string UGenCall(OperatorMatrixPatch patch, bool[] audible);

    /// <inheritdoc />
    public string FileExtension => ".scd";

    /// <inheritdoc />
    public string Export(OperatorMatrixPatch patch, PatchExportOptions? options = null)
    {
        options ??= new PatchExportOptions();
        string name = options.InstrumentName;
        string comments = string.Concat(options.HeaderComments.Select(static c => $"// {c.ReplaceLineEndings(" ")}\n"));
        string text = $$"""
            // Generated by HearSay. Needs SuperCollider with {{Requirement}}; HearSay itself is not needed.
            {{comments}}//
            // Controls: freq (Hz), gate, velocity (0..1), amp, out.
            // Ratio operators follow freq, fixed operators do not.
            // modMatrix[destination][source] is in radians; the diagonal is self-feedback.
            (
            {{ExportSynthDef(patch, name)}}.add;
            )

            """;
        if (options.IncludeUsageExample)
        {
            text += $$"""

                // Play a note:
                (
                fork {
                	var note = Synth(\{{name}}, [\freq, 60.midicps, \velocity, 0.8, \amp, 0.2]);
                	1.5.wait;
                	note.set(\gate, 0);
                };
                )

                // Or play it as an instrument:
                (
                Pbind(
                	\instrument, \{{name}},
                	\midinote, Pseq([48, 55, 60, 64, 67, 72], 2),
                	\velocity, Pwhite(0.5, 1.0),
                	\dur, 0.5,
                	\legato, 0.8,
                	\amp, 0.2
                ).play;
                )

                """;
        }

        return text.ReplaceLineEndings("\n");
    }

    /// <summary>
    /// Returns only the <c>SynthDef(...)</c> expression, without <c>.add</c>, for callers that send the definition to
    /// a server themselves, such as a non-realtime render.
    /// </summary>
    /// <param name="patch">Patch to export.</param>
    /// <param name="synthDefName">Name of the SynthDef.</param>
    /// <exception cref="PatchNotSupportedException">The backend cannot represent the patch.</exception>
    public string ExportSynthDef(OperatorMatrixPatch patch, string synthDefName = "HearSayPatch")
    {
        ArgumentNullException.ThrowIfNull(patch);
        ArgumentException.ThrowIfNullOrWhiteSpace(synthDefName);
        foreach (char c in synthDefName)
        {
            if (!char.IsAsciiLetterOrDigit(c) && c != '_')
            {
                throw new ArgumentException("A SynthDef name may contain ASCII letters, digits and underscores only.", nameof(synthDefName));
            }
        }

        PatchCompatibilityResult compatibility = PatchCompatibilityValidator.Instance.Validate(patch, Capabilities);
        if (!compatibility.IsCompatible)
        {
            throw new PatchNotSupportedException(BackendName, compatibility);
        }

        int n = patch.OperatorCount;
        bool[] audible = patch.FindAudibleOperators();
        bool movingPitch = !patch.Pitch.IsStatic;
        bool needsNote = false;
        for (int i = 0; i < n; i++)
        {
            needsNote |= audible[i] && !patch.Operators[i].KeyScaling.IsNeutral;
        }

        string note = needsNote ? "\n\tvar note = freq.cpsmidi;" : string.Empty;
        string pitch = movingPitch ? $"\n\tvar pitch = ({PitchCents(patch.Pitch)} / 100).midiratio;" : string.Empty;
        string operatorRows = Rows(
            n,
            i => audible[i] ? OperatorRow(patch.Operators[i], movingPitch) : "[0, 0, 0]",
            i => $"OP{i + 1}" + (audible[i] ? string.Empty : patch.Operators[i].Enabled ? " (inaudible)" : " (off)"));
        string modulationRows = Rows(
            n,
            d => $"[{List(n, s => ModulationAmount(patch, audible, s, d))}]",
            d => $"into OP{d + 1}");
        string levels = List(n, i => audible[i] ? Number(patch.OutputLevels[i]) : "0");
        string synthDef = $$"""
            SynthDef(\{{synthDefName}}, { |out = 0, freq = 440, gate = 1, velocity = 1, amp = 0.2|
            	var ctlMatrix, modMatrix, operators, signal;{{note}}{{pitch}}

            	// One row per operator: [frequency, phase, amplitude].
            	ctlMatrix = [
            {{operatorRows}}
            	];

            	// modMatrix[destination][source], radians. Columns: OP1 .. OP{{n}}.
            	modMatrix = [
            {{modulationRows}}
            	];

            	{{UGenCall(patch, audible)}}
            	signal = (operators * [{{levels}}]).sum;

            	// Frees the synth when the note is over.
            	{{Lifetime(patch, audible)}}
            	Out.ar(out, (signal * amp) ! 2);
            })
            """;
        return synthDef.ReplaceLineEndings("\n");
    }

    /// <summary>Comma-separated items, as between the brackets of a SuperCollider array literal.</summary>
    /// <param name="count">Number of items.</param>
    /// <param name="item">The item at an index.</param>
    protected static string List(int count, Func<int, string> item) => string.Join(", ", Enumerable.Range(0, count).Select(item));

    /// <summary>The rows of a matrix literal, one per line and each followed by a comment.</summary>
    private static string Rows(int count, Func<int, string> row, Func<int, string> comment) =>
        string.Join("\n", Enumerable.Range(0, count).Select(i => $"\t\t{row(i)}{(i < count - 1 ? "," : string.Empty)} // {comment(i)}"));

    private static string ModulationAmount(OperatorMatrixPatch patch, bool[] audible, int source, int destination)
    {
        ModulationEdge? edge = patch.ModulationMatrix.Find(source, destination);
        bool live = edge is { Enabled: true } && edge.Amount != 0.0 && audible[source] && audible[destination];
        return live ? EdgeAmount(edge!) : "0";
    }

    private static string OperatorRow(OperatorPatch op, bool movingPitch)
    {
        string frequency;
        if (op.Frequency.Mode == OperatorFrequencyMode.Ratio)
        {
            double factor = op.Frequency.Ratio * Math.Pow(2.0, op.FineTuneCents / 1200.0);
            frequency = $"(freq * {Number(factor)}{(movingPitch ? " * pitch" : string.Empty)})";
            if (op.DetuneHz != 0.0)
            {
                frequency += $" + {Number(op.DetuneHz)}";
            }
        }
        else
        {
            frequency = Number(op.Frequency.FixedFrequencyHz + op.DetuneHz);
        }

        string? timeScale = op.KeyScaling.RatePerOctave != 0.0
            ? $"(2 ** ({Number(-op.KeyScaling.RatePerOctave)} * ((note - {Number(op.KeyScaling.ReferenceMidiNote)}) / 12)))"
            : null;
        string amplitude = EnvGen(op.AmplitudeEnvelope, timeScale);
        if (op.VelocitySensitivity != 0.0)
        {
            amplitude += $" * ({Number(1.0 - op.VelocitySensitivity)} + ({Number(op.VelocitySensitivity)} * velocity))";
        }

        if (op.KeyScaling.LevelDbPerOctave != 0.0)
        {
            amplitude += $" * ({Number(op.KeyScaling.LevelDbPerOctave)} * ((note - {Number(op.KeyScaling.ReferenceMidiNote)}) / 12)).dbamp";
        }

        return $"[{frequency}, {Number(op.InitialPhase)}, {amplitude}]";
    }

    private static string EdgeAmount(ModulationEdge edge) =>
        edge.AmountEnvelope is null
            ? Number(edge.Amount)
            : $"({Number(edge.Amount)} * {EnvGen(edge.AmountEnvelope, null)})";

    private static string PitchCents(PitchModel pitch)
    {
        var parts = new List<string>();
        if (pitch.PitchEnvelope is not null)
        {
            parts.Add(EnvGen(pitch.PitchEnvelope, null));
        }

        if (pitch.Vibrato is { DepthCents: not 0.0 } vibrato)
        {
            string lfo = $"(SinOsc.kr({Number(vibrato.RateHz)}) * {Number(vibrato.DepthCents)}";
            if (vibrato.DelaySeconds > 0 || vibrato.FadeInSeconds > 0)
            {
                lfo += $" * EnvGen.kr(Env([0, 0, 1], [{Number(vibrato.DelaySeconds)}, {Number(vibrato.FadeInSeconds)}]))";
            }

            parts.Add(lfo + ")");
        }

        return "(" + string.Join(" + ", parts) + ")";
    }

    private static string EnvGen(OperatorEnvelope envelope, string? timeScale)
    {
        IEnumerable<EnvelopePoint> segments = envelope.Points.Skip(1);
        string levels = List(envelope.Points.Count, i => Number(envelope.EffectiveLevel(i)));
        string times = string.Join(", ", segments.Select(static p => Number(p.TimeSeconds)));
        string curves = string.Join(", ", segments.Select(static p => p.Curve switch
        {
            EnvelopeCurve.Exponential => "\\exp",
            EnvelopeCurve.Step => "\\step",
            _ => "\\lin",
        }));
        string sustain = envelope.SustainPoint is int point ? $", {point}" : string.Empty;
        string scale = timeScale is null ? string.Empty : $", timeScale: {timeScale}";
        return $"EnvGen.kr(Env([{levels}], [{times}], [{curves}]{sustain}), gate{scale})";
    }

    private static string Lifetime(OperatorMatrixPatch patch, bool[] audible)
    {
        bool sustaining = false;
        double release = 0;
        double oneShot = 0;
        for (int i = 0; i < patch.OperatorCount; i++)
        {
            if (!audible[i] || patch.OutputLevels[i] == 0.0)
            {
                continue;
            }

            OperatorPatch op = patch.Operators[i];
            OperatorEnvelope envelope = op.AmplitudeEnvelope;

            // Key scaling can stretch envelopes; four octaves below the reference note is a generous bound.
            double stretch = Math.Max(1.0, Math.Pow(2.0, Math.Abs(op.KeyScaling.RatePerOctave) * 4.0));
            if (envelope.SustainPoint is null)
            {
                double total = 0;
                for (int p = 1; p < envelope.Points.Count; p++)
                {
                    total += envelope.Points[p].TimeSeconds;
                }

                oneShot = Math.Max(oneShot, total * stretch);
            }
            else
            {
                sustaining = true;
                release = Math.Max(release, envelope.ReleaseSeconds * stretch);
            }
        }

        return sustaining
            ? $"EnvGen.kr(Env.asr(0, 1, {Number(Math.Max(release, oneShot) + 0.05)}, \\lin), gate, doneAction: Done.freeSelf);"
            : $"Line.kr(0, 1, {Number(oneShot + 0.05)}, doneAction: Done.freeSelf);";
    }

    /// <summary>Formats a number as a SuperCollider float literal that reads back as the same 32-bit value.</summary>
    internal static string Number(double value)
    {
        string text = ((float)value).ToString("R", CultureInfo.InvariantCulture);
        if (text.Contains('E', StringComparison.Ordinal))
        {
            // SuperCollider needs a digit on both sides of the decimal point and a lower-case exponent.
            // Through decimal, so that the shortest round-trip digits survive: 1E-05 becomes 0.00001.
            text = decimal.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out decimal exact)
                ? exact.ToString("0.0###########################", CultureInfo.InvariantCulture)
                : ((double)(float)value).ToString("0.0###############", CultureInfo.InvariantCulture);
        }
        else if (!text.Contains('.', StringComparison.Ordinal))
        {
            text += ".0";
        }

        return text;
    }
}
